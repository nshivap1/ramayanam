#!/usr/bin/env node
// Generates src/app/registry.gen.ts and src/app/styles.gen.css by scanning src/games/* (and labs/*).
// Contributors never edit a central list: add a folder, run `npm run gen` (build/dev/test do it for you).
import { existsSync, readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

function gameDirs(base) {
  const dir = join(root, base);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((n) => !n.startsWith('_') && !n.startsWith('.') && statSync(join(dir, n)).isDirectory())
    .filter((n) => existsSync(join(dir, n, 'manifest.ts')) && existsSync(join(dir, n, 'Game.tsx')))
    .sort();
}

/** Registry + stylesheet sources. `only` (array of ids) restricts the build to those games — used for isolated per-game checks. */
export function registrySources({ only } = {}) {
  const keep = (id) => !only || only.includes(id);
  const games = gameDirs('src/games').filter(keep).map((id) => ({ id, base: '../games' }));
  const labs = gameDirs('labs').filter(keep).map((id) => ({ id, base: '../../labs' }));
  const all = [...games, ...labs];
  const ident = (id) => 'm_' + id.replace(/[^a-zA-Z0-9]/g, '_');

  const ts = [
    '// GENERATED by tools/gen-registry.mjs — do not edit. Add a game by creating src/games/<id>/.',
    "import type { GameEntry } from '@sdk';",
    ...all.map((g) => `import { manifest as ${ident(g.id)} } from '${g.base}/${g.id}/manifest';`),
    '',
    'export const GAMES: readonly GameEntry[] = [',
    ...all.map((g) => `  { manifest: ${ident(g.id)}, load: () => import('${g.base}/${g.id}/Game') },`),
    '];',
    '',
  ].join('\n');

  const css = [
    '/* GENERATED by tools/gen-registry.mjs — do not edit. */',
    "@import '../ui/tokens.css';",
    "@import '../ui/ui.css';",
    "@import './app.css';",
    ...all.filter((g) => existsSync(join(root, 'src/app', g.base, g.id, 'style.css'))).map((g) => `@import '${g.base}/${g.id}/style.css';`),
    '',
  ].join('\n');
  return { ts, css, games: games.map((g) => g.id), labs: labs.map((g) => g.id) };
}

/** Writes the generated files (needed by the type-checker; bundling uses registrySources directly). */
export function generate({ quiet = false } = {}) {
  const { ts, css, games, labs } = registrySources();
  const write = (rel, content) => {
    const p = join(root, rel);
    if (!existsSync(p) || readFileSync(p, 'utf8') !== content) writeFileSync(p, content);
  };
  write('src/app/registry.gen.ts', ts);
  write('src/app/styles.gen.css', css);
  if (!quiet) console.log(`registry: ${games.length} games, ${labs.length} labs`);
  return { games, labs };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) generate();
