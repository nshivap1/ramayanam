/**
 * Read-only loaders for the reference datasets ("oracles") used to derive and cross-check
 * nominal paradigms. Only data files are read; no code from the datasets is executed.
 *
 * Location: env SAMSKURU_ORACLES (default /home/claude/refs/data).
 *
 * Every loader returns paradigms as 24 cells, index = (vibhakti-1)*3 + (vacana-1), vibhakti 8 = sambodhana,
 * each cell a list of SLP1 forms in the oracle's own order, spelling-normalised by `canon`.
 */
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { devaToSlp1 } from '../../../../src/sanskrit/translit.ts';
import { canon, natva, natvaFrom } from './slp.ts';

export const ORACLE_ROOT = process.env.SAMSKURU_ORACLES ?? '/home/claude/refs/data';

export const ORACLE_FILES = {
  ashtadhyayi: 'ashtadhyayi-com_data/shabda/data2.txt',
  huet: 'sanskrit-lexicon_csl-inflect/huetdata/nominals/huet_noun_tables.txt',
  pydeclPron: 'sanskrit-lexicon_csl-inflect/nominals/pydecl/decline_pron_data.txt',
  pydeclCard: 'sanskrit-lexicon_csl-inflect/nominals/pydecl/decline_card_data.txt',
  pydeclIrr: 'sanskrit-lexicon_csl-inflect/nominals/pydecl/decline_irr_data.txt',
  kaleEndings: 'sanskrit_data/learnsanskrit.org/nominal-endings-inflected.csv',
  kalePronouns: 'sanskrit_data/learnsanskrit.org/pronouns-inflected.csv',
  kaleSarvanamas: 'sanskrit_data/learnsanskrit.org/sarvanamas-inflected.csv',
  kaleNouns: 'sanskrit_data/learnsanskrit.org/nouns-irregular-inflected.csv',
  kaleAdjectives: 'sanskrit_data/learnsanskrit.org/adjectives-irregular-inflected.csv',
} as const;

export function oraclesAvailable(): boolean {
  return Object.values(ORACLE_FILES).every((f) => existsSync(join(ORACLE_ROOT, f)));
}

export type Cells = string[][]; // 24 cells

function read(rel: string): string {
  return readFileSync(join(ORACLE_ROOT, rel), 'utf8');
}

function emptyCells(): Cells {
  return Array.from({ length: 24 }, () => [] as string[]);
}

function uniq(xs: string[]): string[] {
  return [...new Set(xs)];
}

// ---------------------------------------------------------------------------------------------
// A — ashtadhyayi.com shabda/data2.txt (generated by vidyut-prakriya; Devanagari)
// ---------------------------------------------------------------------------------------------
export interface AshtEntry {
  urlid: string;
  word: string;
  linga: string;
  cells: Cells;
}
let ashtCache: Map<string, AshtEntry> | undefined;
export function loadAshtadhyayi(): Map<string, AshtEntry> {
  if (ashtCache) return ashtCache;
  const json = JSON.parse(read(ORACLE_FILES.ashtadhyayi)) as { data: { urlid: string; word: string; linga: string; forms: string }[] };
  const map = new Map<string, AshtEntry>();
  for (const e of json.data) {
    const raw = e.forms.split(';');
    if (raw.length !== 24) continue;
    const cells = raw.map((cell) =>
      uniq(
        cell
          .split('-')
          .map((f) => f.trim().replace(/^हे\s+/, ''))
          .filter((f) => f.length > 0)
          .map((f) => canon(devaToSlp1(f))),
      ),
    );
    map.set(e.urlid, { urlid: e.urlid, word: e.word, linga: e.linga, cells });
  }
  ashtCache = map;
  return map;
}

// ---------------------------------------------------------------------------------------------
// H — Gérard Huet's Sanskrit Heritage declensions as extracted by csl-inflect (SLP1)
// ---------------------------------------------------------------------------------------------
function parseColonTable(s: string): Cells | undefined {
  const raw = s.split(':');
  if (raw.length !== 24) return undefined;
  return raw.map((cell) =>
    uniq(
      cell
        .split('/')
        .map((f) => f.trim())
        .filter((f) => f.length > 0)
        .map(canon),
    ),
  );
}
let huetCache: Map<string, Cells> | undefined;
/** key: `${stem} ${gender}` with gender m | f | n | d (deictic: asmad, yuzmad) */
export function loadHuet(): Map<string, Cells> {
  if (huetCache) return huetCache;
  const map = new Map<string, Cells>();
  for (const line of read(ORACLE_FILES.huet).split('\n')) {
    const i = line.indexOf(':');
    if (i < 0) continue;
    const cells = parseColonTable(line.slice(i + 1));
    if (cells) map.set(line.slice(0, i), cells);
  }
  huetCache = map;
  return map;
}

// ---------------------------------------------------------------------------------------------
// C — csl-inflect "pydecl" hand-entered tables (pronouns, cardinals, irregulars) (SLP1)
// ---------------------------------------------------------------------------------------------
let pydeclCache: Map<string, Cells> | undefined;
/** key: `${stem},${model}` e.g. `tad,m_pron`, `paYcan,m_card`, `saKi,m_irr` (hyphens in stems removed) */
export function loadPydecl(): Map<string, Cells> {
  if (pydeclCache) return pydeclCache;
  const map = new Map<string, Cells>();
  for (const file of [ORACLE_FILES.pydeclPron, ORACLE_FILES.pydeclCard, ORACLE_FILES.pydeclIrr]) {
    for (const line of read(file).split('\n')) {
      if (line.startsWith(';') || !line.includes('\t')) continue;
      const [key, table] = line.split('\t');
      if (!key || !table) continue;
      const cells = parseColonTable(table);
      if (cells) map.set(key.replace(/-/g, ''), cells);
    }
  }
  pydeclCache = map;
  return map;
}

// ---------------------------------------------------------------------------------------------
// K — learnsanskrit.org CC0 tables, hand-entered from M. R. Kale, A Higher Sanskrit Grammar (SLP1, pre-sandhi)
// ---------------------------------------------------------------------------------------------
interface KaleRow {
  stem: string;
  stemGenders: string;
  form: string;
  gender: string;
  vibhakti: number;
  vacana: number;
}
function parseKaleCsv(rel: string): KaleRow[] {
  const rows: KaleRow[] = [];
  const lines = read(rel).split('\n');
  for (const line of lines.slice(1)) {
    const p = line.trim().split(',');
    if (p.length < 6) continue;
    const vacana = { s: 1, d: 2, p: 3 }[p[5] ?? ''];
    const vibhakti = Number(p[4]);
    if (!vacana || !(vibhakti >= 1 && vibhakti <= 8)) continue;
    rows.push({ stem: p[0] ?? '', stemGenders: p[1] ?? '', form: p[2] ?? '', gender: p[3] ?? '', vibhakti, vacana });
  }
  return rows;
}
let kaleDirectCache: Map<string, Cells> | undefined;
/**
 * Whole-word tables (pronouns, sarvanāmas, irregular nouns and adjectives).
 * key: `${stem} ${formGender}` with formGender m | f | n | none.
 * The raw data is pre-sandhi (final s, no retroflexion): `canon` + `natva` are applied.
 */
export function loadKaleDirect(): Map<string, Cells> {
  if (kaleDirectCache) return kaleDirectCache;
  const map = new Map<string, Cells>();
  for (const file of [ORACLE_FILES.kalePronouns, ORACLE_FILES.kaleSarvanamas, ORACLE_FILES.kaleNouns, ORACLE_FILES.kaleAdjectives]) {
    for (const r of parseKaleCsv(file)) {
      const key = `${r.stem} ${r.gender}`;
      let cells = map.get(key);
      if (!cells) map.set(key, (cells = emptyCells()));
      const cell = cells[(r.vibhakti - 1) * 3 + (r.vacana - 1)]!;
      const f = natva(canon(r.form));
      if (!cell.includes(f)) cell.push(f);
    }
  }
  kaleDirectCache = map;
  return map;
}

let kaleEndingsCache: Map<string, Cells> | undefined;
/** Ending tables. key: `${stemType} ${gender}` e.g. `a m`, `I f`, `an n`; cells hold raw endings (pre-sandhi). */
export function loadKaleEndings(): Map<string, Cells> {
  if (kaleEndingsCache) return kaleEndingsCache;
  const map = new Map<string, Cells>();
  for (const r of parseKaleCsv(ORACLE_FILES.kaleEndings)) {
    if (r.stemGenders !== r.gender) continue;
    const key = `${r.stem} ${r.gender}`;
    let cells = map.get(key);
    if (!cells) map.set(key, (cells = emptyCells()));
    const cell = cells[(r.vibhakti - 1) * 3 + (r.vacana - 1)]!;
    if (!cell.includes(r.form)) cell.push(r.form);
  }
  kaleEndingsCache = map;
  return map;
}

/**
 * Declines a regular stem with Kale's ending table: the stem-final sound(s) named by `stemType`
 * are replaced by each ending; of the n/ṇ ending pairs the table lists, only the one that
 * satisfies the ṇatva rule for this stem is kept.
 */
export function declineWithKaleEndings(stem: string, stemType: string, gender: string): Cells | undefined {
  const endings = loadKaleEndings().get(`${stemType} ${gender}`);
  if (!endings) return undefined;
  if (!stem.endsWith(stemType)) return undefined;
  const base = stem.slice(0, stem.length - stemType.length);
  return endings.map((cell) =>
    uniq(
      cell
        .map((e) => canon(base + e))
        .filter((f) => f === natvaFrom(base + f.slice(base.length).replace(/R/g, 'n'), base.length)),
    ),
  );
}
