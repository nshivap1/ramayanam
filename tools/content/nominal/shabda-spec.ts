import type { Gender, Level } from '../../../src/content/types.ts';

export type Kind = 'noun' | 'pronoun' | 'numeral' | 'adjective';

export interface ShabdaSpec {
  id: string;
  /** prātipadika, Devanagari */
  stem: string;
  gender: Gender;
  genderless?: boolean;
  kind: Kind;
  anta: string;
  en: string;
  level: Level;
  /** ashtadhyayi.com urlid when (word, liṅga) is ambiguous there or the headword differs (e.g. feminine pronoun stems) */
  a?: string;
  /** Huet table key `${slp1stem} ${gender}` when it differs from the default; `-` = do not use */
  h?: string;
  /** csl-inflect pydecl key, e.g. `tad,m_pron` */
  c?: string;
  /** learnsanskrit (Kale) whole-word table key, e.g. `tad m`, `paYcan none` */
  k?: string;
  /** learnsanskrit (Kale) ending table to apply to the stem, e.g. `a m`; `-` = do not use */
  ke?: string;
  /** model paradigm (ashtadhyayi.com urlid + its stem in SLP1) declined by stem substitution when the stem itself is not a headword there */
  model?: { urlid: string; stem: string };
  /** forms attested by a single source family that are nevertheless accepted, with the reason (cell = `${vibhakti}.${vacana}`) */
  accept?: Record<string, { forms: string[]; why: string }>;
  /** preferred display form per cell (`${vibhakti}.${vacana}` → Devanagari) when the default ordering rules are not enough */
  first?: Record<string, string>;
}

