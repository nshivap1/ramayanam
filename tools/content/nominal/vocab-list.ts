/**
 * Hand-authored candidate vocabulary for the VOCAB pack: everyday words a Samskrita Bharati learner meets.
 * This list was written from general knowledge of common spoken-Sanskrit vocabulary — it is NOT copied from any
 * picture dictionary or word list. Nothing here ships as-is: `gen-vocab.ts` keeps an entry only when the
 * dictionaries confirm the stem and its gender (nouns), the indeclinable (avyayas), the conjugated form (verbs)
 * or every word of the phrase; entries that fail are dropped and reported.
 *
 * Builders
 *   N(stem, gender, gloss, level, emoji?, opts?)   noun — stem is the prātipadika; the citation form is derived
 *   A(stem, gloss, level, emoji?, opts?)           adjective (three genders; cited in the masculine nominative)
 *   I(word, gloss, level, emoji?, opts?)           indeclinable (avyaya), cited as-is
 *   V(form, gloss, infinitive, level, emoji?, opts?)  verb in laṭ prathama-puruṣa ekavacana; `infinitive` is the English
 *                                                  keyword looked up in the dhātupāṭha meaning (e.g. 'go')
 *   R(form, gloss, level, paradigm, cell)          pronoun form, verified against a SHABDA cell (e.g. 'asmad', '1.1')
 *   P(text, gloss, level, opts?)                   phrase; every word (or `parts` of a sandhied word) must be a verified form
 *
 * opts
 *   modern: true     — an established modern Samskrita Bharati coinage that classical dictionaries lack (kept at level ≥ 1,
 *                      tagged usage:samskrita-bharati). Use only when certain. `head` (the last member of the compound)
 *                      must then be a dictionary word of the same gender.
 *   sense: true      — a dictionary word used in a modern sense (घटी 'clock'): gender/spelling are dictionary-verified,
 *                      the gloss is modern usage.
 *   kw: [...]        — English keywords to look for in the dictionary definition when the gloss itself is not a dictionary word
 *   head: 'फल'       — head of a transparent compound, verified instead of the whole when the whole is not a headword
 *   id: '...'        — explicit id (otherwise derived from the stem)
 */
import type { Gender, Level } from '../../../src/content/types.ts';

export type Pos = 'noun' | 'adjective' | 'avyaya' | 'verb' | 'pronoun' | 'numeral' | 'phrase';

export interface Opts {
  modern?: boolean;
  sense?: boolean;
  kw?: string[];
  head?: string;
  id?: string;
  /** verbs: upasarga + unprefixed base form, e.g. { pre: 'आ', base: 'गच्छति' } */
  pre?: string;
  base?: string;
  /** verbs: Monier-Williams key (SLP1) of the prefixed root, used to confirm the meaning */
  root?: string;
  /** phrases: the unsandhied words of the phrase when a token is a sandhi of several words */
  parts?: string[];
}

export interface Candidate {
  pos: Pos;
  /** nouns/adjectives: stem; others: the word / form / phrase itself */
  word: string;
  gender?: Gender;
  en: string;
  level: Level;
  emoji?: string;
  category: string;
  opts: Opts;
  /** verbs: English infinitive keyword; pronouns: paradigm id + cell */
  kw?: string;
  paradigm?: string;
  cell?: string;
}

type Row = Omit<Candidate, 'category'>;

export const N = (word: string, gender: Gender, en: string, level: Level, emoji?: string, opts: Opts = {}): Row => ({ pos: 'noun', word, gender, en, level, emoji, opts });
export const A = (word: string, en: string, level: Level, emoji?: string, opts: Opts = {}): Row => ({ pos: 'adjective', word, en, level, emoji, opts });
export const I = (word: string, en: string, level: Level, emoji?: string, opts: Opts = {}): Row => ({ pos: 'avyaya', word, en, level, emoji, opts });
export const V = (word: string, en: string, kw: string, level: Level, emoji?: string, opts: Opts = {}): Row => ({ pos: 'verb', word, en, kw, level, emoji, opts });
export const R = (word: string, en: string, level: Level, paradigm: string, cell: string): Row => ({ pos: 'pronoun', word, en, level, paradigm, cell, opts: {} });
export const P = (word: string, en: string, level: Level, opts: Opts = {}): Row => ({ pos: 'phrase', word, en, level, opts });

export interface CategorySpec {
  id: string;
  sa: string;
  en: string;
  emoji: string;
  rows: Row[];
}

