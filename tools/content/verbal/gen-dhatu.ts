/**
 * Generates src/content/dhatu/data.ts and src/content/dhatu/verification-report.json
 * from the oracles. Usage:
 *
 *   SAMSKURU_ORACLES=/path/to/refs node --import tsx tools/content/verbal/gen-dhatu.ts
 *
 * The output is deterministic; re-running with unchanged oracles must leave git clean.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Lakara, Pada } from '../../../src/content/types';
import { buildAll, LAKARAS, loadOracles, TAG_A, TAG_B, TAG_C, TAG_D, TAG_RULE, type BuiltDhatu } from './dhatu-build';
import { buildPrefixed, type BuiltPrefixed } from './prefixed-build';

const OUT_DIR = fileURLToPath(new URL('../../../src/content/dhatu/', import.meta.url));

const q = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

/** One paradigm on one line: cells separated by spaces, puruṣas by ' | ', alternates by '/', empty cell '—'. */
export function packTable(rows: string[][]): string {
  const cells = rows.map((c) => (c.length === 0 ? '—' : c.join('/')));
  return [cells.slice(0, 3).join(' '), cells.slice(3, 6).join(' '), cells.slice(6, 9).join(' ')].join(' | ');
}

function emitDhatu(b: BuiltDhatu): string {
  const { spec, ash } = b;
  const lines: string[] = [];
  lines.push('  {');
  const head = [
    `id: ${q(spec.id)}`,
    `dhatu: ${q(spec.dhatu)}`,
    `gana: ${spec.gana}`,
    `pada: ${q(spec.pada)}`,
    `level: ${spec.level}`,
    `en: ${q(spec.en)}`,
    `artha: ${q(ash.artha)}`,
    `upadesha: ${q(ash.aupadeshik)}`,
    `dhatupatha: ${q(spec.baseindex)}`,
  ];
  lines.push(`    ${head.join(', ')},`);
  if (spec.note) lines.push(`    note: ${q(spec.note)},`);
  lines.push('    forms: {');
  for (const lakara of LAKARAS) {
    const byPada = b.forms[lakara];
    if (!byPada) continue;
    const parts: string[] = [];
    for (const pada of ['P', 'A'] as Pada[]) {
      const t = byPada[pada];
      if (t) parts.push(`${pada}: ${q(packTable(t))}`);
    }
    if (parts.length === 1) lines.push(`      ${lakara}: { ${parts[0]} },`);
    else {
      lines.push(`      ${lakara}: {`);
      for (const p of parts) lines.push(`        ${p},`);
      lines.push('      },');
    }
  }
  lines.push('    },');
  const k = Object.entries(b.krdanta).map(([field, forms]) => `${field}: ${q(forms.join('/'))}`);
  lines.push(`    krdanta: { ${k.join(', ')} },`);
  if (b.lyap.length > 0) {
    lines.push('    lyap: [');
    for (const l of b.lyap) lines.push(`      { upasarga: ${q(l.upasarga)}, form: ${q(l.form)}, en: ${q(l.en)} },`);
    lines.push('    ],');
  }
  const tags = [TAG_A];
  if (b.stats.byB > 0) tags.push(TAG_B);
  if (b.stats.byC > 0 || Object.values(b.krdantaEvidence).some((a) => a.some((x) => x.c))) tags.push(TAG_C);
  if (Object.values(b.krdantaEvidence).some((a) => a.some((x) => x.d)) || b.lyap.length > 0) tags.push(TAG_D);
  if (Object.keys(b.krdanta).some((f) => f !== 'ktva' && f !== 'tumun')) tags.push(TAG_RULE);
  lines.push(`    evidence: { forms: ${b.stats.forms}, sanskritverb: ${b.stats.byB}, heritage: ${b.stats.byC} },`);
  lines.push(`    verifiedBy: [${tags.map(q).join(', ')}],`);
  lines.push('  },');
  return lines.join('\n');
}

function emitPrefixed(p: BuiltPrefixed): string {
  return `  { id: ${q(p.id)}, upasarga: ${q(p.upasarga)}, base: ${q(p.base)}, lat3s: ${q(p.lat3s)}, en: ${q(p.en)}, level: ${p.level}, verifiedBy: [${p.verifiedBy.map(q).join(', ')}] },`;
}

function main(): void {
  const o = loadOracles();
  const built = buildAll(o).filter((b) => {
    // a dhātu must at least have a complete laṭ paradigm in its primary pada to be shipped
    const pada: Pada = b.spec.pada === 'A' ? 'A' : 'P';
    const lat = b.forms.lat?.[pada];
    return lat !== undefined && lat.every((c) => c.length > 0);
  });
  const shippedIds = new Set(built.map((b) => b.spec.id));
  const prefixed = buildPrefixed(o, built);

  const header = `/**
 * GENERATED FILE — do not edit by hand.
 * Regenerate: node --import tsx tools/content/verbal/gen-dhatu.ts   (see tools/content/verbal/README.md)
 *
 * Every finite form below is present in the same paradigm cell of the ashtadhyayi.com dhātu
 * tables (generated by vidyut-prakriya) AND of at least one independent engine (SanskritVerb,
 * Sanskrit Heritage). \`evidence\` = [number of finite forms shipped, how many of them
 * SanskritVerb confirms, how many Sanskrit Heritage confirms].
 *
 * Paradigm string: prathama | madhyama | uttama puruṣa; within each, eka dvi bahu vacana;
 * '/' separates accepted alternates (the first is the form to display); '—' = cell withheld.
 */
import type { RawDhatu, RawPrefixed } from './types';

export const DHATU_DATA: readonly RawDhatu[] = [
${built.map(emitDhatu).join('\n')}
];

export const PREFIXED_DATA: readonly RawPrefixed[] = [
${prefixed.accepted.map(emitPrefixed).join('\n')}
];
`;
  writeFileSync(OUT_DIR + 'data.ts', header);

  const total = { dhatus: built.length, cells: 0, forms: 0, sanskritverb: 0, heritage: 0, both: 0, onlySanskritverb: 0, onlyHeritage: 0 };
  for (const b of built) {
    total.cells += b.stats.cells;
    total.forms += b.stats.forms;
    total.sanskritverb += b.stats.byB;
    total.heritage += b.stats.byC;
    total.both += b.stats.byBoth;
  }
  total.onlySanskritverb = total.sanskritverb - total.both;
  total.onlyHeritage = total.heritage - total.both;
  const krt = { forms: 0, heritage: 0, dcs: 0, both: 0 };
  for (const b of built) {
    for (const arr of Object.values(b.krdantaEvidence)) {
      for (const x of arr) {
        krt.forms++;
        if (x.c) krt.heritage++;
        if (x.d) krt.dcs++;
        if (x.c && x.d) krt.both++;
      }
    }
  }
  const report = {
    generated: 'tools/content/verbal/gen-dhatu.ts',
    totals: total,
    krdanta: krt,
    lyap: built.reduce((n, b) => n + b.lyap.length, 0),
    prefixed: { accepted: prefixed.accepted.length, rejected: prefixed.rejected },
    notShipped: buildAll(o)
      .filter((b) => !shippedIds.has(b.spec.id))
      .map((b) => b.spec.id),
    perDhatu: built.map((b) => ({
      id: b.spec.id,
      sanskritverbRoot: b.svRoot ?? null,
      heritageRoots: b.heritageRoots,
      forms: b.stats.forms,
      sanskritverb: b.stats.byB,
      heritage: b.stats.byC,
    })),
    singleEngine: built.filter((b) => b.stats.byB === 0 || b.stats.byC === 0).map((b) => ({ id: b.spec.id, confirmedOnlyBy: b.stats.byB === 0 ? 'sanskrit-heritage' : 'sanskritverb' })),
    droppedCells: built.flatMap((b) => b.stats.droppedCells),
    droppedForms: built.flatMap((b) => b.stats.droppedForms),
    multiFormCells: built.flatMap((b) => b.stats.multi),
  };
  writeFileSync(OUT_DIR + 'verification-report.json', JSON.stringify(report, null, 1) + '\n');
  console.log(JSON.stringify({ ...total, krdanta: krt, lyap: report.lyap, prefixed: prefixed.accepted.length, prefixedRejected: prefixed.rejected.length, droppedCells: report.droppedCells.length, droppedForms: report.droppedForms.length, notShipped: report.notShipped }, null, 1));
}

void (LAKARAS as Lakara[]);
main();
