/** code → 7 rows of 5-bit masks (bit 4 = leftmost). */
export const GLYPHS: Map<number, number[]> = (() => {
  const m = new Map<number, number[]>();
  for (const [chars, rows] of BANDS) {
    const split = rows.map((r) => r.split(' '));
    for (let i = 0; i < chars.length; i++) {
      const g: number[] = [];
      for (let r = 0; r < 7; r++) {
        const cell = split[r]?.[i] ?? '.....';
        let v = 0;
        for (let k = 0; k < 5; k++) if (cell[k] === '#') v |= 1 << (4 - k);
        g.push(v);
      }
      m.set(chars.charCodeAt(i), g);
    }
  }
  return m;
})();

