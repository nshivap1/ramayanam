function parse(table: string): string[][][] {
  return table
    .trim()
    .split('\n')
    .map((line) =>
      line
        .trim()
        .split(/\s+/)
        .map((cell) => (cell === '-' ? [] : cell.split('/'))),
    );
}

for (const [id, table] of Object.entries(GOLDEN)) {
  test(`golden table: ${id}`, () => {
    const p = shabda(id);
    assert.ok(p, `paradigm ${id} is missing`);
    const expected = parse(table);
    assert.equal(expected.length, 8, 'golden table must have 8 rows');
    for (const row of expected) assert.equal(row.length, 3, 'golden row must have 3 cells');
    assert.deepEqual(
      p.forms.map((row) => row.map((cell) => [...cell])),
      expected,
    );
  });
}

test('the golden set covers the paradigms named in the pack brief', () => {
  for (const id of ['rama-m', 'phala-n', 'rama-f', 'hari-m', 'nadi-f', 'guru-m', 'pitri-m', 'rajan-m', 'tad-m', 'asmad', 'yushmad']) assert.ok(GOLDEN[id], id);
});
