/**
 * SHABDA — verified declension paradigms (śabda-rūpāṇi).
 *
 * Every cell holds only forms that two independent reference datasets agree on; see ./README.md
 * for the derivation, conventions and known gaps, and ./REVIEW.md for the human sign-off status.
 */
import type { Forms, Level, PackMeta, Vacana, Vibhakti } from '../types';
import { SHABDA_DATA } from './data';
import type { ShabdaParadigm } from './types';

export type { ShabdaParadigm } from './types';

/** All paradigms, in teaching order (vowel stems, consonant stems, pronouns, numerals). */
export const SHABDA: readonly ShabdaParadigm[] = SHABDA_DATA;

const BY_ID: ReadonlyMap<string, ShabdaParadigm> = new Map(SHABDA.map((p) => [p.id, p]));
const EMPTY: Forms = Object.freeze([]);

/** Looks a paradigm up by id (e.g. 'rama-m', 'tad-f', 'asmad'). */
export function shabda(id: string): ShabdaParadigm | undefined {
  return BY_ID.get(id);
}

/**
 * Accepted forms of one cell, display form first; `[]` when the cell does not exist.
 * @example form(shabda('rama-m')!, 3, 1) // → ['रामेण']
 */
export function form(p: ShabdaParadigm, v: Vibhakti, n: Vacana): Forms {
  return p.forms[v - 1]?.[n - 1] ?? EMPTY;
}

/** Cumulative: every paradigm a learner at `level` has met (p.level <= level). */
export function shabdaForLevel(level: Level): ShabdaParadigm[] {
  return SHABDA.filter((p) => p.level <= level);
}

